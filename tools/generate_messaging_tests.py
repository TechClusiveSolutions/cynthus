PLACEHOLDERS = [
    ('device', 'device_biometric_trend'), ('device', 'device_tracker_breached'),
    ('lifestyle', 'user_energy_record'), ('lifestyle', 'user_sentiment_record'),
]


def render(template, **values):
    text = template.replace('@@MARKER@@', MARKER)

    for key, value in values.items():
        text = text.replace(f'@@{key}@@', value)

    return text.rstrip('\n') + '\n'


def modules():
    names = []

    for path in sorted(SRC.rglob('*.py')):
        parts = list(path.relative_to(SRC).with_suffix('').parts)

        if parts[-1] == '__init__':
            parts = parts[:-1]

        if parts:
            names.append('.'.join(parts))

    return names


def build():
    files = {'conftest.py': render(CONFTEST), '../pytest.ini': PYTEST_INI}
    listing = '[\n' + ''.join(f"    '{name}',\n" for name in modules()) + ']'
    files['test_package_structure.py'] = render(STRUCTURE, MODULES=listing)

    for component, module, class_name, payload_module, payload_class, event_type, fields in MESSAGES:
        field_args = ', '.join(f'{name}={sample}' for name, sample in fields.items())
        dict_fields = ', '.join(f"'{name}': {sample}" for name, sample in fields.items())
        files[f'component/{component}/payloads/test_{payload_module}.py'] = render(
            PAYLOAD_TEST, COMPONENT=component, MODULE=payload_module, CLASS=payload_class,
            FIELDS=field_args)
        files[f'component/{component}/message/test_{module}.py'] = render(
            MESSAGE_TEST, COMPONENT=component, MODULE=module, CLASS=class_name, PAYLOAD_MODULE=payload_module,
            PAYLOAD_CLASS=payload_class, EVENT_TYPE=event_type,
            FIELDS=field_args, DICT_FIELDS=dict_fields)

    files['test_cynthus_messaging.py'] = render(NAMESPACE_TEST, DOTTED='cynthus.messaging', DEPTH='0')
    files['test_cynthus_messaging_component.py'] = render(NAMESPACE_TEST, DOTTED='cynthus.messaging.component', DEPTH='1')

    for component, module in PLACEHOLDERS:
        files[f'component/{component}/message/test_{module}.py'] = render(PLACEHOLDER_TEST, COMPONENT=component, MODULE=module)

    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--dry-run', action='store_true')
    args = parser.parse_args()

    files = build()

    for relative, text in sorted(files.items()):
        target = (REPO / 'test' / relative).resolve()
        print(f'  {"would write" if args.dry_run else "wrote"}  {target.relative_to(ROOT)}')

        if not args.dry_run:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding='utf-8', newline='\n')

    print(f'\n{len(files)} files')

    return 0


if __name__ == '__main__':
    sys.exit(main())
