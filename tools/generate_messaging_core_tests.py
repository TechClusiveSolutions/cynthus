def render(template, **values):
    text = template.replace('@@MARKER@@', MARKER)

    for key, value in values.items():
        text = text.replace(f'@@{key}@@', value)

    return text.rstrip('\n') + '\n'


def camel(parts):
    return ''.join(part.capitalize() for part in parts.split('_'))


def signal_names():
    return [(aggregate, action) for aggregate, action in SIGNALS]


def signal_class(aggregate, action):
    return f'PublicMeal{camel(aggregate)}{camel(action)}Signal'


def signal_module(aggregate, action):
    return f'public_meal_{aggregate}_{action}'


def signal_exports():
    names = ['EnergyLevel', 'LifecycleAction', 'DecisionReason', 'SignalActionType', 'SignalDomainType',
             'SignalTriggerType', 'SignalMessage', 'SignalPayload']
    names += [signal_class(aggregate, action) for aggregate, action in SIGNALS]

    return names


