def conftest_text():
    payload_leaves = ''.join(f"    ({spec[0]!r}, {spec[1]!r}),\n" for spec in PAYLOADS.values())
    message_leaves = ''.join(f"    ('message.{spec[2]}', {spec[3]!r}),\n" for spec in PAYLOADS.values())

    return render(CONFTEST, PAYLOAD_LEAVES=payload_leaves.rstrip('\n'), MESSAGE_LEAVES=message_leaves.rstrip('\n'))


def write(path, text, dry_run):
    print(f'  {"would write" if dry_run else "wrote"}  {path.relative_to(ROOT)}')

    if dry_run:
        return

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8', newline='\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--dry-run', action='store_true')
    args = parser.parse_args()

    write(REPO / 'pytest.ini', PYTEST_INI, args.dry_run)
    write(REPO / 'test' / 'conftest.py', conftest_text(), args.dry_run)

    files = build_files()

    for relative, text in sorted(files.items()):
        write(TEST_ROOT / relative, text, args.dry_run)

    print(f'\n{len(files) + 2} files')

    return 0


if __name__ == '__main__':
    sys.exit(main())
