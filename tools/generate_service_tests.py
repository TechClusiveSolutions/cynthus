def render(template, **values):
    text = template.replace('@@MARKER@@', MARKER)

    for key, value in values.items():
        text = text.replace(f'@@{key}@@', value)

    return text.rstrip('\n') + '\n'


def modules_in(src_dir, package):
    """Dotted names of every module (and package) below src/<package>."""

    names = []

    for path in sorted((src_dir / package).rglob('*.py')):
        parts = list(path.relative_to(src_dir).with_suffix('').parts)

        if parts[-1] == '__init__':
            parts = parts[:-1]

        names.append('.'.join(parts))

    return names


def write(path, text, dry_run, written):
    if path.exists() and path.name != 'conftest.py':
        existing = path.read_text(encoding='utf-8')

        if MARKER not in existing and existing.strip():
            print(f'  keep   {path.relative_to(ROOT)} (hand-written)')

            return

    written.append(path)

    if dry_run:
        print(f'  would write {path.relative_to(ROOT)}')

        return

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8', newline='\n')
    print(f'  wrote  {path.relative_to(ROOT)}')


def generate(spec, dry_run):
    base = container_dir(spec)
    test_dir = base / 'test'
    pkg, kind = spec['pkg'], spec['kind']
    src_dir = base / 'src'
    files = {}
    written = []

    # ---- conftest --------------------------------------------------------------------
    blocks = ''
    signal = spec.get('signal')

    if signal:
        blocks += render(CONFTEST_MESSAGING, TOPIC_CLASS=signal['topic'], SUB_CLASS=signal['sub'],
                         SUB_NAME=signal['name'])

    if spec.get('azure'):
        blocks += render(CONFTEST_AZURE)

    files['conftest.py'] = render(CONFTEST, LABEL=label(spec), PKG=pkg, EXTRA_BLOCKS=blocks.rstrip('\n'))
    files['../pytest.ini'] = PYTEST_INI

    # ---- structure -------------------------------------------------------------------
    if kind != 'scheduler':
        names = modules_in(src_dir, pkg)
        listing = '[\n' + ''.join(f"    '{name}',\n" for name in names) + ']'
        known = repr({pkg}) if kind == 'broken_init' else 'set()'
        files['test_package_structure.py'] = render(STRUCTURE, LABEL=label(spec), PKG=pkg, MODULES=listing,
                                                    KNOWN_BROKEN=known)

    # ---- entry point -----------------------------------------------------------------
    if kind == 'lifespan':
        files[f'test_{pkg}_init.py'] = render(LIFESPAN_INIT, PKG=pkg, CONFIG_LOG=spec['config_log'])
    elif kind == 'plain':
        files[f'test_{pkg}_init.py'] = render(PLAIN_INIT, PKG=pkg, CONFIG_LOG=spec['config_log'])
    elif kind == 'broken_init':
        files[f'test_{pkg}_init.py'] = render(BROKEN_INIT, PKG=pkg)
    elif kind == 'scheduler':
        files['test_scheduler_init.py'] = render(SCHEDULER_INIT)
    elif kind == 'worker':
        files['test_worker_init.py'] = render(WORKER_INIT)
        files['test_tasks_periodic_init.py'] = render(WORKER_PERIODIC)

    # ---- routes ----------------------------------------------------------------------
    if kind in ('lifespan', 'plain', 'broken_init'):
        has_event = bool(spec.get('event'))
        has_signal = bool(signal)
        has_system = bool(spec.get('system'))
        tests, imports = '', ''

        if has_event:
            imports = 'from faststream.redis.fastapi import RedisRouter\n'
            template = ROUTES_INIT_EVENT_AZURE if spec.get('azure') else ROUTES_INIT_EVENT
            tests += render(template, PKG=pkg)

        if has_signal:
            tests += render(ROUTES_INIT_SIGNAL, PKG=pkg)

        if has_system:
            tests += render(ROUTES_INIT_SYSTEM, PKG=pkg)

        files['test_routes_init.py'] = render(ROUTES_INIT, PKG=pkg, RS_IMPORT=imports.rstrip('\n'),
                                              TESTS=tests.rstrip('\n'))

        if has_system:
            extra = SYSTEM_LOGGING if spec['system'] == 'logistics' else ''
            files['test_routes_system.py'] = render(SYSTEM, PKG=pkg, EXTRA=extra)

        event = spec.get('event')

        if event == 'logistics':
            files['test_routes_event.py'] = render(EVENT_LOGISTICS)
        elif event == 'analysis':
            files['test_routes_event.py'] = render(EVENT_ANALYSIS)
        elif event:
            files['test_routes_event.py'] = render(
                EVENT_STD, PKG=pkg, CHANNEL=event['channel'], HANDLER=event['handler'], LOG=event['log'])

        if signal:
            extra = SIGNAL_LOGISTICS_EXTRA if pkg == 'logistics' else ''
            files['test_routes_signal.py'] = render(SIGNAL, PKG=pkg, EXTRA=extra)
            topic, sub = signal['topic'], signal['sub']
            files['test_signal_contract.py'] = render(
                SIGNAL_CONTRACT, TOPIC_CLASS=topic, SUB_CLASS=sub, NAMES=f'{topic} and {sub}')

    if spec.get('azure'):
        files['test_analysis_messaging.py'] = render(ANALYSIS_MESSAGING)
        files['test_azure_broker_contract.py'] = render(AZURE_CONTRACT)

    if pkg == 'logistics':
        files['test_testing_fixture_service_bus_client.py'] = render(LOGISTICS_FIXTURE_CLIENT)
        files['test_testing_fixture_service_bus_message.py'] = render(LOGISTICS_FIXTURE_MESSAGE)
        files['test_testing_fixture_signal_receiver.py'] = render(LOGISTICS_FIXTURE_RECEIVER)

    for name, text in files.items():
        target = (test_dir / name).resolve()
        write(target, text if text.endswith('\n') else text + '\n', dry_run, written)

    return written


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--dry-run', action='store_true')
    args = parser.parse_args()

    total = 0

    for spec in CONTAINERS:
        print(label(spec))
        total += len(generate(spec, args.dry_run))

    print(f'\n{total} files {"planned" if args.dry_run else "written"}')

    return 0


if __name__ == '__main__':
    sys.exit(main())
